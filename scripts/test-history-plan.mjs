vm.runInContext(code,ctx);
const api=vm.runInContext('HistoryPlan',ctx);
await api.mount(root);
assert.match(root.innerHTML,/Sources and the ancient timeline/);
const click=dataset=>root.onclick({target:{closest:()=>({dataset})}});
