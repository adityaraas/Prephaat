import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import vm from 'node:vm';
const data = JSON.parse(await readFile('public/data/history-plan.json','utf8'));
const code = await readFile('public/history-plan.js','utf8');
assert.deepEqual(data.segments.map(s=>s.days.length),[20,15,25]);
const days = data.segments.flatMap(s=>s.days);
assert.deepEqual(days.map(d=>d.day),Array.from({length:60},(_,i)=>i+1));
for(const d of days){
  assert.equal(d.notes.length,3);
  assert.ok(d.notes.every(n=>n.length>100),`Day ${d.day} lacks teaching material`);
  assert.ok(d.recall && d.recallAnswer && d.task && d.reading);
  assert.ok(d.studyWords >= 220, `Day ${d.day} lacks expanded prose`);
  assert.ok(d.deepReading.length);
  for (const id of d.deepReading) {
    const topic=data.dossiers[id];
    assert.ok(topic.sections.length>=3 && topic.comparison.rows.length>=4 && topic.terms.length>=3 && topic.timeline.length>=3);
    assert.ok(topic.trap && topic.practice.question && topic.practice.answer);
  }
  for(const id of d.sources) assert.ok(data.sources[id]);
  if(d.day>=36) assert.ok(d.sources.includes('ncert12c') && d.sources.includes('spectrum'));
}
for(const s of data.segments) for(const stage of ['Prelims','Mains']) assert.ok(data.pyqs.some(q=>q.segment===s.id && q.stage===stage));
for(const q of data.pyqs) assert.equal(new URL(q.url).hostname,'www.upsc.gov.in');
